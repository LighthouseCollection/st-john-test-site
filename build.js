/* St. John the Beloved test site · the build (build.js): site/ → public/.
     site/boot.js and the modules it imports (main.jsx, site.jsx, data.js, pages.js, screens/*.jsx) → public/app.js, one plain
       script with a small module table; "react", "react-dom" and "plenix-platform" are the scripts the page already loaded
       from the CDN (window.React, window.ReactDOM, window.Plenix), like any outside app of Plenix.
     site/index.html → public/index.html (the server fills in the Plenix address); site/assets/ → public/assets/.
   The build fails, and writes nothing, if a file does not compile or an import does not resolve.
     node build.js */
const fs = require('fs');
const path = require('path');
const Babel = require('@babel/standalone');

const ROOT = __dirname;
const SITE = path.join(ROOT, 'site');
const OUT = path.join(ROOT, 'public');
const EXTERNALS = { react: 'window.React', 'react-dom': 'window.ReactDOM', 'react-dom/client': 'window.ReactDOM', 'plenix-platform': 'window.Plenix' };
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

function resolve(from, spec) {
  const base = path.resolve(path.dirname(from), spec);
  for (const c of [base, base + '.js', base + '.jsx']) if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
  throw new Error('Cannot resolve "' + spec + '" from ' + rel(from));
}

function bundle(entry) {
  const modules = new Map(), order = [];
  const visit = (file) => {
    if (modules.has(file)) return;
    let code;
    try {
      code = Babel.transform(fs.readFileSync(file, 'utf8'), { filename: file, sourceType: 'module', presets: [['react', { runtime: 'classic' }]], plugins: [['transform-modules-commonjs', { strictMode: false }]] }).code;
    } catch (e) { throw new Error(rel(file) + ' does not compile: ' + e.message); }
    const entryInfo = { id: rel(file), code, deps: {} };
    modules.set(file, entryInfo);
    for (const m of code.matchAll(/\brequire\((["'])([^"']+)\1\)/g)) {
      const spec = m[2];
      if (EXTERNALS[spec]) { entryInfo.deps[spec] = { external: EXTERNALS[spec] }; continue; }
      if (!spec.startsWith('.')) throw new Error('Only relative imports and react, react-dom, plenix-platform: ' + spec + ' in ' + rel(file));
      const dep = resolve(file, spec); entryInfo.deps[spec] = { id: rel(dep) }; visit(dep);
    }
    order.push(entryInfo);
  };
  visit(entry);
  const defs = order.map((m) => {
    const table = JSON.stringify(Object.fromEntries(Object.entries(m.deps).map(([k, v]) => [k, v.id || null])));
    const ext = Object.entries(m.deps).filter(([, v]) => v.external).map(([k, v]) => JSON.stringify(k) + ': function () { return ' + v.external + '; }').join(', ');
    return '  ' + JSON.stringify(m.id) + ': { deps: ' + table + ', externals: { ' + ext + ' }, run: function (module, exports, require) {\n' + m.code + '\n  } }';
  }).join(',\n');
  return '/* GENERATED by build.js from site/ (St. John the Beloved test site) */\n(function () {\n  var defs = {\n' + defs + '\n  };\n  var cache = {};\n'
    + '  function load(id) {\n    if (cache[id]) return cache[id].exports;\n    var def = defs[id], module = { exports: {} };\n    cache[id] = module;\n'
    + '    def.run(module, module.exports, function (spec) {\n      if (def.externals[spec]) { var g = def.externals[spec](); if (!g) throw new Error(\'St. John: "\' + spec + \'" is not loaded before app.js\'); return g; }\n      return load(def.deps[spec]);\n    });\n    return module.exports;\n  }\n'
    + '  load(' + JSON.stringify(rel(entry)) + ');\n})();\n';
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) { const a = path.join(from, e.name), b = path.join(to, e.name); if (e.isDirectory()) copyDir(a, b); else fs.copyFileSync(a, b); }
}

try {
  const app = bundle(path.join(SITE, 'boot.js'));
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'app.js'), app);
  fs.copyFileSync(path.join(SITE, 'index.html'), path.join(OUT, 'index.html'));
  copyDir(path.join(SITE, 'assets'), path.join(OUT, 'assets'));
  console.log('Built public/app.js (' + Math.round(app.length / 1024) + ' KB), public/index.html and public/assets/');
} catch (e) {
  console.error('BUILD FAILED, nothing was written: ' + e.message);
  process.exit(1);
}
